function rows(league, values) {
  return values.map(([team, played, won, draw, lost, points], index) => ({
    id: `standing-${slug(league)}-${index + 1}`,
    league,
    position: index + 1,
    team,
    played,
    won,
    draw,
    lost,
    points,
  }))
}

function match(id, league, home, away, score, time, venue, status) {
  return { id, league, home, away, score, time, venue, status }
}

function player(id, name, club, position, nationality, birthDate, goals, assists) {
  return { id, name, club, position, nationality, birthDate, goals, assists }
}

function slug(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}
